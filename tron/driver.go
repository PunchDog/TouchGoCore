package tron

// DriverTronGrid 是「出款直接上链」这一类驱动的标识名。
//
// 名字留在本包而不是 pay：pay 是零实现依赖的契约叶子包，把某条链的接入点名字
// 写进它的常量表，等于让契约层反过来知道 TRON 的事。
//
// 它的用途只剩一个：配置里 tron.usdt.driver 必须写成这个名字，否则装配期就拒。
// 这是为了防止「配置写着换实现、实际还是这一套」静默通过——本仓已没有第二条
// 出款实现，所以这个字段更像一次显式确认，而不是分发键。
//
// 曾经与它同住的 init()（向 pay 注册驱动工厂）随注册表一起消失：装配就是本包
// 直接构造 onchainChannel，不再有「谁都可以按名字重新造一条通道」的入口。
const DriverTronGrid = "tron_trongrid"
